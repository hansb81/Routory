-- discover_cities_seed.sql — '어디로 떠나볼까요' 추천 후보 도시 풀 시드 (027_discover_cities.sql 다음에 실행)
--
-- 국내 9곳 + 해외 18곳, 총 27개 도시. 반구가 달라 계절이 반대인 도시(시드니·괌·리우데자네이루)는 한국
-- 겨울이 그쪽 여름이라는 점을 반영해 점수를 매겼다. 12개월 전부 "어느 달을 골라도 추천 후보가 10개
-- 이상" 나오도록 월별로 분포를 맞췄다(이 파일 맨 아래 "월별 후보 수 검증" 표 참고) — 027의
-- discover_country_cap()(나라당 최대 4개) 적용 후에도 모든 달이 10개 이상으로 남는다.
--
-- 재실행 안전성(요청 5번, upsert):
--   - destinations: unique(country_code, name_en)에 on conflict do nothing — 이미 있으면 그대로 둔다.
--   - discover_cities: unique(destination_id)에 on conflict do update — tagline만 갱신, is_active를
--     true로 되돌린다(재실행으로 비활성화가 풀리는 건 의도된 동작 — 이 시드가 다루는 27개 도시는 항상
--     "활성"이어야 하므로).
--   - discover_city_months: PK(city_id, month)에 on conflict do update — score/reason_tag/reason_text를
--     최신 값으로 덮어쓴다.
--   - city_highlights: 자연 키가 없어서(각 행이 그냥 uuid) on conflict를 쓸 수 없다 — 대신 이 시드가
--     다루는 27개 도시의 하이라이트를 delete 후 insert한다(멱등성 보장, 중복 없음). **주의**: 관리
--     페이지가 나중에 생겨 이 도시들의 하이라이트를 직접 수정해 놨다면, 이 시드를 다시 돌리면 그 수정이
--     이 파일의 값으로 되돌아간다 — 재실행은 "초기 시드 상태로 리셋"을 의미한다는 걸 알고 있어야 한다.
--
-- 모든 점수(score)·소개 문구(tagline/reason_text/summary)는 이후 관리 페이지에서 직접 수정 가능한
-- 초기값이다 — "일반적으로 알려진 계절 정보"만 썼고, 정확한 날짜가 해마다 바뀌는 축제성 항목은
-- reason_text 안에 "(정확한 날짜는 해마다 달라요)"라고 표시해 뒀다. 그 목록은 파일 맨 아래 주석 참고.
--
-- 실행 방법: Supabase 대시보드 → SQL Editor에 통째로 붙여 넣고 실행한다. 027_discover_cities.sql이
-- 먼저 적용돼 있어야 한다(discover_cities/discover_city_months/city_highlights 테이블 필요).

-- ==========================================================================
-- 0. 국내 9개 도시 — destinations에 아직 없으므로 새로 추가한다
-- ==========================================================================
-- destinations.region의 체크 제약(014_destinations.sql)에 'domestic' 값이 없다 — 'other'를 쓴다
-- (country_currency도 KR을 region='other'로 분류해 둬서 일관된다). 이 테이블에 국내 도시가 들어가도
-- destinations.js#DOMESTIC_CITIES(여행 만들기 1단계의 국내 탭)는 전혀 건드리지 않는다 — 그 탭은 이
-- 테이블을 조회하지 않고 코드 상수를 그대로 쓰기 때문이다(screen-main.md 참고). 좌표는 016의 해외
-- 프리셋과 같은 수준으로 손으로 확인한 도시 중심 좌표다.

